/// Search countries by name (case-insensitive partial match).
List<WorldCountry> searchCountries(String query) {
  if (query.isEmpty) return kWorldCountries;
  final q = query.toLowerCase();
  return kWorldCountries
      .where((c) => c.name.toLowerCase().contains(q) || c.code.toLowerCase().contains(q))
      .toList();
}
